#!/usr/bin/env bash
set -euo pipefail

# ============================================================
# Add New Application Policy to OpenBao
# Use this for new apps after bootstrap (NOT for first setup)
#
# Usage:
#   ./01-add-app-policy.sh myapp
# ============================================================

OPENBAO_CONTAINER="openbao"
OPENBAO_ADDR="http://127.0.0.1:8200"

OPENBAO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
POLICIES_DIR="${OPENBAO_DIR}/policies"
BOOTSTRAP_DIR="${OPENBAO_DIR}/bootstrap"

AGENT_UID=100
AGENT_GID=1000

# ============================================================
# HELPERS
# ============================================================

die() {
    echo "[ERROR] $*" >&2
    exit 1
}

info() {
    echo "[INFO] $*"
}

ok() {
    echo "[ OK ] $*"
}

bao() {
    docker exec \
        -e BAO_ADDR="${OPENBAO_ADDR}" \
        "${OPENBAO_CONTAINER}" \
        bao "$@"
}

# ============================================================
# INPUT VALIDATION
# ============================================================

[[ $# -eq 1 ]] || die "Usage: $0 <app-name>"

APP_NAME="$1"

[[ "${APP_NAME}" =~ ^[a-z0-9-]+$ ]] || \
    die "Invalid app name: ${APP_NAME} (use lowercase alphanumeric characters and hyphens)"

# ============================================================
# PRECHECKS
# ============================================================

echo
echo "============================================================"
echo " Add New Application Policy"
echo "============================================================"
echo "App: ${APP_NAME}"
echo "============================================================"
echo

docker inspect "${OPENBAO_CONTAINER}" >/dev/null 2>&1 || \
    die "Container '${OPENBAO_CONTAINER}' not found"

[[ "$(docker inspect -f '{{.State.Running}}' "${OPENBAO_CONTAINER}")" == "true" ]] || \
    die "Container '${OPENBAO_CONTAINER}' is not running"

info "Checking OpenBao status..."

status="$(bao status 2>&1 || true)"

echo "${status}" | grep -q "Initialized.*true" || \
    die "OpenBao is not initialized"

echo "${status}" | grep -q "Sealed.*false" || \
    die "OpenBao is sealed"

ok "OpenBao is ready"

# ============================================================
# AUTHENTICATION CHECK
# ============================================================

if ! bao token lookup >/dev/null 2>&1; then
    echo
    echo "[WARN] Not authenticated to OpenBao"
    echo "Enter root token to proceed (NOT stored):"
    echo

    read -rsp "Root token: " root_token
    echo

    [[ -n "${root_token}" ]] || die "Token cannot be empty"

    docker exec \
        -e BAO_ADDR="${OPENBAO_ADDR}" \
        "${OPENBAO_CONTAINER}" \
        bao login -no-print "${root_token}" >/dev/null || \
        die "Authentication failed"

    unset root_token

    ok "Authenticated"
fi

# ============================================================
# CREATE POLICY FILE TEMPLATE
# ============================================================

mkdir -p "${POLICIES_DIR}" "${BOOTSTRAP_DIR}"

POLICY_FILE="${POLICIES_DIR}/${APP_NAME}-policy.hcl"

if [[ -f "${POLICY_FILE}" ]]; then
    echo
    ok "Policy file already exists: ${POLICY_FILE}"

    read -rp "Overwrite? [y/N]: " confirm
    [[ "${confirm}" =~ ^[Yy]$ ]] || exit 0
fi

echo
echo "Creating policy template for: ${APP_NAME}"
echo

cat > "${POLICY_FILE}" <<EOF
# ============================================================
# Policy: ${APP_NAME}
# Generated by: 01-add-app-policy.sh
#
# Edit this file to define what secrets ${APP_NAME} can access
# ============================================================

# Allow ${APP_NAME} to read its own secrets
path "secret/data/${APP_NAME}/*" {
  capabilities = ["read", "list"]
}

# Allow ${APP_NAME} to read shared secrets
path "secret/data/shared/*" {
  capabilities = ["read", "list"]
}

# Allow metadata reads for ${APP_NAME}
path "secret/metadata/${APP_NAME}/*" {
  capabilities = ["read", "list"]
}

EOF

ok "Policy template created: ${POLICY_FILE}"

echo
echo "Edit this file to define secret access, then run:"
echo
echo "  docker exec -i ${OPENBAO_CONTAINER} bao policy write ${APP_NAME}-policy - < ${POLICY_FILE}"
echo

read -rp "Load policy now? [y/N]: " confirm

if [[ "${confirm}" =~ ^[Yy]$ ]]; then
    info "Loading policy..."

    docker exec -i \
        -e BAO_ADDR="${OPENBAO_ADDR}" \
        "${OPENBAO_CONTAINER}" \
        bao policy write "${APP_NAME}-policy" - < "${POLICY_FILE}" >/dev/null

    ok "Policy loaded: ${APP_NAME}-policy"
fi

# ============================================================
# SETUP APPROLE (OPTIONAL)
# ============================================================

read -rp "Create AppRole for ${APP_NAME}? [y/N]: " setup_approle

if [[ "${setup_approle}" =~ ^[Yy]$ ]]; then
    info "Configuring AppRole: ${APP_NAME}"

    bao write "auth/approle/role/${APP_NAME}" \
        token_policies="${APP_NAME}-policy,shared-policy" \
        token_ttl="1h" \
        token_max_ttl="4h" \
        secret_id_ttl="0" \
        secret_id_num_uses="0" >/dev/null

    ok "AppRole created: ${APP_NAME}"

    role_id="$(
        bao read \
            -field=role_id \
            "auth/approle/role/${APP_NAME}/role-id"
    )"

    secret_id="$(
        bao write \
            -field=secret_id \
            -f \
            "auth/approle/role/${APP_NAME}/secret-id"
    )"

    role_dir="${BOOTSTRAP_DIR}/${APP_NAME}"

    mkdir -p "${role_dir}"

    chown "${AGENT_UID}:${AGENT_GID}" "${role_dir}"
    chmod 700 "${role_dir}"

    printf '%s\n' "${role_id}" > "${role_dir}/role-id"
    chown "${AGENT_UID}:${AGENT_GID}" "${role_dir}/role-id"
    chmod 600 "${role_dir}/role-id"

    printf '%s\n' "${secret_id}" > "${role_dir}/secret-id"
    chown "${AGENT_UID}:${AGENT_GID}" "${role_dir}/secret-id"
    chmod 600 "${role_dir}/secret-id"

    ok "AppRole credentials saved:"
    echo "  ${role_dir}/role-id"
    echo "  ${role_dir}/secret-id"
fi

# ============================================================
# SUMMARY
# ============================================================

echo
echo "============================================================"
echo " Application Added"
echo "============================================================"
echo
echo "App: ${APP_NAME}"
echo
echo "Policy file:"
echo "  ${POLICY_FILE}"
echo
echo "Next steps:"
echo
echo "1. Edit the policy file as needed."
echo
echo "2. Use OpenBao UI to create secrets:"
echo "   http://192.168.1.106:8200/ui/vault/secrets/secret/list/${APP_NAME}/"
echo
echo "3. If AppRole was created, credentials are stored at:"
echo "   ${BOOTSTRAP_DIR}/${APP_NAME}/role-id"
echo "   ${BOOTSTRAP_DIR}/${APP_NAME}/secret-id"
echo
echo "============================================================"